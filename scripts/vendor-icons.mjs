#!/usr/bin/env node
/**
 * Vendors the Lucide glyphs referenced by src/renderer/src/ui/iconMap.ts
 * into src/renderer/src/ui/lucide.tsx.
 *
 *   node scripts/vendor-icons.mjs [lucide-static-version]
 *
 * Re-run after adding ids to iconMap.ts. Lucide is ISC-licensed; only the inner SVG
 * geometry is copied here — size, stroke width and color live in Icon.tsx / styles.css.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const VERSION = process.argv[2] ?? '1.58.0'

/** Hand-tuned replacements, keyed by Lucide name (raw JSX for the icon's children). */
const OVERRIDES = {}

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const mapPath = join(root, 'src/renderer/src/ui/iconMap.ts')
const outPath = join(root, 'src/renderer/src/ui/lucide.tsx')

const map = readFileSync(mapPath, 'utf8')
const names = [...new Set([...map.matchAll(/^\s*'?[a-z0-9-]+'?:\s*'([a-z0-9-]+)',\s*$/gm)].map((m) => m[1]))].sort()
if (!names.length) throw new Error(`no icon names found in ${mapPath}`)

const toJsx = (svg) =>
  svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/ class="[^"]*"/g, '')
    .replace(/\s+/g, ' ') // collapse to one line
    .replace(/([a-z]+)-([a-z-]+)=/g, (_, a, rest) => `${a}${rest.replace(/-([a-z])/g, (_, c) => c.toUpperCase())}=`) // stroke-width -> strokeWidth
    .trim()

const glyphs = {}
const failed = []
for (const name of names) {
  if (OVERRIDES[name]) { glyphs[name] = OVERRIDES[name]; continue }
  const url = `https://unpkg.com/lucide-static@${VERSION}/icons/${name}.svg`
  const res = await fetch(url)
  if (!res.ok) { failed.push(`${name} (${res.status})`); continue }
  glyphs[name] = toJsx(await res.text())
}
if (failed.length) throw new Error(`not found in lucide-static@${VERSION}: ${failed.join(', ')}`)

const body = names.map((n) => `  '${n}': (<>${glyphs[n]}</>),`).join('\n')
writeFileSync(outPath, `/**
 * Generated by scripts/vendor-icons.mjs from lucide-static@${VERSION} (ISC license).
 * Do not edit: change src/renderer/src/ui/iconMap.ts and re-run the script.
 */
export const LUCIDE = {
${body}
}
`)
console.log(`wrote ${names.length} icons to ${outPath}`)
